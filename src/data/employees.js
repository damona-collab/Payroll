// Enrich employees with calculated payroll data
export const employees = rawEmployees.map(emp => {
  const payroll = calculatePayroll({
    basicSalary: emp.basicSalary,
    allowances: emp.allowances,
    housingAllowance: emp.housingAllowance,
    pensionEmployee: emp.pensionEmployee,
    medicalAid: emp.medicalAid,
    otherDeductions: emp.otherDeductions,
  })

  const startDate = new Date(emp.startDate)
  const now = new Date()
  const monthsEmployed = Math.floor(
    (now - startDate) / (1000 * 60 * 60 * 24 * 30.44)
  )
  const leaveAccrual = calculateLeaveAccrual(monthsEmployed)

  return {
    ...emp,
    payroll,
    monthsEmployed,
    leaveBalance: {
      annual: Math.max(0, leaveAccrual.annual - Math.floor(Math.random() * 5)),
      sick: Math.max(0, leaveAccrual.sick - Math.floor(Math.random() * 3)),
      familyResponsibility: 5,
    },
  }
})

